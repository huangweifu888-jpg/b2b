const SUSPECT_PATTERNS = [
  /\uFFFD/,
  /Ã[^\s]{0,3}/,
  /Â[^\s]{0,3}/,
  /Ð[^\s]{0,3}/,
  /Ñ[^\s]{0,3}/,
  /[\u00C0-\u017F]{3,}/,
];

export function repairKnownMojibake(value: string) {
  return KNOWN_MOJIBAKE_REPLACEMENTS.reduce(
    (result, [from, to]) => result.split(from).join(to),
    value
  );
}

export function isLikelyMojibake(value?: string | null) {
  if (!value) return false;
  const text = value.trim();
  if (!text) return false;
  if (/^\?+$/.test(text)) return true;
  if (SUSPECT_PATTERNS.some((pattern) => pattern.test(text))) return true;
  if (/\?{2,}/.test(text)) return true;
  return SUSPECT_FRAGMENTS.some((fragment) => text.includes(fragment));
}

export function sanitizeDisplayText(value?: string | null, fallback = "") {
  if (!value) return fallback;
  const repaired = repairKnownMojibake(value).trim();
  if (!repaired) return fallback;
  return isLikelyMojibake(repaired) ? fallback : repaired;
}

export function sanitizeSummaryText(value?: string | null, fallback = "") {
  const cleaned = sanitizeDisplayText(value, fallback);
  return cleaned ? cleaned.replace(/\s+/g, " ").trim() : "";
}

export function pickCleanText(candidates: Array<string | null | undefined>, fallback = "") {
  for (const candidate of candidates) {
    const cleaned = sanitizeDisplayText(candidate);
    if (cleaned) return cleaned;
  }
  return fallback;
}
